	def GillespieSSAshorttime(self,initial,T):
		# Shape: initial: [1,         N_species]
		#        A,B    : [N_species, N_reaction]
		#        c      : [1,         N_reaction]
		S = self.nu.T
		harzardf = lambda x: self.a(0,x,self.ks)
		x = initial
		t = 0
		while(t<T):
			xl = np.copy(x)
			
			a = harzardf(x)
			# print(a)
			a0 = np.sum(a)
			if abs(a0)<1e-8:
				break
			tau = np.random.exponential(1/a0)
			r2 = np.random.uniform(0,1)
			r = self.findinteger(np.cumsum(a)/a0,r2)
			x = x + S[:,int(r)]
			t = t+tau
		return xl

	def findinteger(self,a,k):
	    # a is an increasing sequence
	    # find i such that a[i]<k<a[i+1]
	    re = np.where((a[:-1]<k)*(a[1:]>=k))[0]
	    if len(re)==1:
	        return re[0]+1
	    else:
	        return 0

